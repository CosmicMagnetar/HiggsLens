from __future__ import annotations

"""HiggsLens: artifact-based dashboard for a reproducible HIGGS benchmark.

Run: streamlit run higgs_lens_app.py
Expected artifacts (generated by notebooks/01_midsem_mvp.ipynb):
- results.csv
- val_predictions.csv
- test_predictions.csv
- run_metadata.json (optional)
- permutation_importance.csv (optional)

The app does not train on the test data. It chooses the operating threshold from
validation scores and reports performance at that frozen threshold on test scores.
"""
from pathlib import Path
import json
import numpy as np
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
from sklearn.metrics import (
    roc_auc_score, average_precision_score, brier_score_loss,
    precision_score, recall_score, f1_score, confusion_matrix,
    roc_curve, precision_recall_curve
)
from higgslens.core import select_threshold_for_recall, summarize_at_threshold
from sklearn.calibration import calibration_curve

st.set_page_config(page_title="HiggsLens", page_icon="⚛️", layout="wide")
st.title("HiggsLens")
st.caption("Reproducible ML benchmark and operating-point explorer for simulated HIGGS events")
st.warning("Educational research prototype. UCI HIGGS is simulated Monte Carlo data. This dashboard is not a particle-discovery system or a production detector service.")

ARTIFACT_DIR = Path("higgs_project_outputs")

def load_uploaded_or_local(upload, local_path, **kwargs):
    if upload is not None:
        return pd.read_csv(upload, **kwargs)
    if local_path.exists():
        return pd.read_csv(local_path, **kwargs)
    return None

def read_json_upload(upload, local_path):
    if upload is not None:
        return json.load(upload)
    if local_path.exists():
        return json.loads(local_path.read_text(encoding="utf-8"))
    return {}

with st.sidebar:
    st.header("Load experiment artifacts")
    st.write("Upload the files from the notebook output folder, or put them in `higgs_project_outputs/` next to this app.")
    results_upload = st.file_uploader("results.csv", type=["csv"], key="results")
    val_upload = st.file_uploader("val_predictions.csv", type=["csv"], key="val")
    test_upload = st.file_uploader("test_predictions.csv", type=["csv"], key="test")
    importance_upload = st.file_uploader("permutation_importance.csv (optional)", type=["csv"], key="importance")
    metadata_upload = st.file_uploader("run_metadata.json (optional)", type=["json"], key="metadata")

results = load_uploaded_or_local(results_upload, ARTIFACT_DIR / "results.csv")
val_df = load_uploaded_or_local(val_upload, ARTIFACT_DIR / "val_predictions.csv")
test_df = load_uploaded_or_local(test_upload, ARTIFACT_DIR / "test_predictions.csv")
importance_df = load_uploaded_or_local(importance_upload, ARTIFACT_DIR / "permutation_importance.csv")
metadata = read_json_upload(metadata_upload, ARTIFACT_DIR / "run_metadata.json")

if val_df is None or test_df is None:
    st.info("Run `notebooks/01_midsem_mvp.ipynb` first, then upload `val_predictions.csv` and `test_predictions.csv` from its output ZIP. `results.csv` and feature importance add more context but are optional.")
    with st.expander("Expected prediction-file format"):
        st.code("label,Logistic Regression | Low-level (21),...\n0,0.21,...\n1,0.83,...")
        st.write("First column is the true binary label (0=background, 1=signal); every remaining column is a model's predicted signal probability. Validation and test files must contain matching model columns.")
    st.stop()

for frame_name, frame in [("validation", val_df), ("test", test_df)]:
    if "label" not in frame.columns:
        st.error(f"{frame_name} predictions file must contain a `label` column.")
        st.stop()
    if frame["label"].isna().any() or not set(frame["label"].unique()).issubset({0, 1}):
        st.error(f"{frame_name} label column must contain only 0/1 values.")
        st.stop()

models = [c for c in val_df.columns if c != "label" and c in test_df.columns]
if not models:
    st.error("No matching model probability columns found in validation and test files.")
    st.stop()

if results is not None and "Model" not in results.columns:
    st.warning("The uploaded results.csv has no `Model` column; model-level metrics will be calculated from prediction files.")

st.subheader("Experiment context")
c1, c2, c3, c4 = st.columns(4)
c1.metric("Rows loaded in run", f"{metadata.get('rows_loaded', 'not provided')}")
c2.metric("Input features", str(metadata.get("feature_count", "28 by default")))
c3.metric("Models with matching scores", str(len(models)))
c4.metric("Threshold target", "80% signal efficiency by default")
if metadata:
    with st.expander("Run metadata"):
        st.json(metadata)

st.divider()
st.subheader("Compare models")
# Compute test metrics once, using each model's score column.
metric_rows = []
for model in models:
    yv = val_df["label"].astype(int).to_numpy()
    pv = pd.to_numeric(val_df[model], errors="coerce").to_numpy()
    yt = test_df["label"].astype(int).to_numpy()
    pt = pd.to_numeric(test_df[model], errors="coerce").to_numpy()
    if not (np.isfinite(pv).all() and np.isfinite(pt).all()):
        continue
    target_recall = 0.80
    threshold = select_threshold_for_recall(yv, pv, target_recall=target_recall)
    test_summary = summarize_at_threshold(yt, pt, threshold)
    tn, fp, fn, tp = test_summary["tn"], test_summary["fp"], test_summary["fn"], test_summary["tp"]
    pred = (pt >= threshold).astype(int)
    metric_rows.append({
        "Model": model,
        "Validation ROC-AUC": roc_auc_score(yv, pv),
        "Test ROC-AUC": roc_auc_score(yt, pt),
        "Test average precision": average_precision_score(yt, pt),
        "Threshold (validation; >=80% signal efficiency)": threshold,
        "Test signal efficiency / recall": recall_score(yt, pred, zero_division=0),
        "Test background rejection": tn / max(tn + fp, 1),
        "Test precision": precision_score(yt, pred, zero_division=0),
        "Test F1": f1_score(yt, pred, zero_division=0),
        "Test Brier": brier_score_loss(yt, pt),
    })
metric_df = pd.DataFrame(metric_rows).sort_values("Validation ROC-AUC", ascending=False)
if results is not None and "Model" in results.columns:
    enrich_cols = [c for c in ["Model", "Feature set", "Features", "Train_seconds", "Inference_ms_per_1000"] if c in results.columns]
    if len(enrich_cols) > 1:
        metric_df = metric_df.merge(results[enrich_cols].drop_duplicates("Model"), on="Model", how="left")
st.dataframe(metric_df, use_container_width=True, hide_index=True)
st.download_button("Download calculated comparison CSV", metric_df.to_csv(index=False).encode("utf-8"), file_name="higgslens_comparison.csv", mime="text/csv")

st.divider()
st.subheader("Operating-point explorer")
left, right = st.columns([1, 2])
with left:
    chosen_model = st.selectbox("Model", models, index=0)
    target_eff = st.slider("Target signal efficiency on validation", min_value=0.50, max_value=0.98, value=0.80, step=0.01)

    yv = val_df["label"].astype(int).to_numpy()
    pv = pd.to_numeric(val_df[chosen_model], errors="coerce").to_numpy()
    yt = test_df["label"].astype(int).to_numpy()
    pt = pd.to_numeric(test_df[chosen_model], errors="coerce").to_numpy()
    threshold = select_threshold_for_recall(yv, pv, target_recall=target_eff)
    test_summary = summarize_at_threshold(yt, pt, threshold)
    tn, fp, fn, tp = test_summary["tn"], test_summary["fp"], test_summary["fn"], test_summary["tp"]
    pred = (pt >= threshold).astype(int)
    st.metric("Frozen threshold from validation", f"{threshold:.5f}")
    st.caption("This validation-derived threshold is transferred unchanged to the test split.")
with right:
    m1, m2, m3, m4 = st.columns(4)
    m1.metric("Test signal efficiency", f"{recall_score(yt, pred, zero_division=0):.1%}")
    m2.metric("Test background rejection", f"{tn / max(tn + fp, 1):.1%}")
    m3.metric("Test precision", f"{precision_score(yt, pred, zero_division=0):.1%}")
    m4.metric("Test F1", f"{f1_score(yt, pred, zero_division=0):.3f}")
    cm = pd.DataFrame([[tn, fp], [fn, tp]], index=["Actual background", "Actual signal"], columns=["Pred background", "Pred signal"])
    st.write("Confusion matrix at the frozen threshold")
    st.dataframe(cm, use_container_width=True)

st.divider()
st.subheader("Ranking and calibration diagnostics")
yt = test_df["label"].astype(int).to_numpy()
pt = pd.to_numeric(test_df[chosen_model], errors="coerce").to_numpy()
c1, c2 = st.columns(2)
with c1:
    fpr, tpr, _ = roc_curve(yt, pt)
    fig, ax = plt.subplots(figsize=(5.6, 4.2))
    ax.plot(fpr, tpr, label=f"ROC-AUC={roc_auc_score(yt, pt):.3f}")
    ax.plot([0, 1], [0, 1], linestyle="--", label="Random ranking")
    ax.set_xlabel("False positive rate")
    ax.set_ylabel("True positive rate")
    ax.set_title("Held-out test ROC")
    ax.legend()
    fig.tight_layout()
    st.pyplot(fig)
with c2:
    precision, recall, _ = precision_recall_curve(yt, pt)
    fig, ax = plt.subplots(figsize=(5.6, 4.2))
    ax.plot(recall, precision, label=f"AP={average_precision_score(yt, pt):.3f}")
    ax.axhline(float(np.mean(yt)), linestyle="--", label="Test signal prevalence")
    ax.set_xlabel("Recall")
    ax.set_ylabel("Precision")
    ax.set_title("Held-out test precision-recall")
    ax.legend()
    fig.tight_layout()
    st.pyplot(fig)

frac_pos, mean_pred = calibration_curve(yt, pt, n_bins=10, strategy="quantile")
fig, ax = plt.subplots(figsize=(6, 4.5))
ax.plot(mean_pred, frac_pos, marker="o", label=chosen_model)
ax.plot([0, 1], [0, 1], linestyle="--", label="Perfect calibration")
ax.set_xlabel("Mean predicted probability")
ax.set_ylabel("Observed signal fraction")
ax.set_title("Test reliability diagram")
ax.legend()
fig.tight_layout()
st.pyplot(fig)
st.caption("Brier score combines calibration and discrimination effects; interpret it together with the reliability diagram. The benchmark's signal fraction is not a real-collider prior probability.")

if importance_df is not None and {"feature", "importance_mean"}.issubset(importance_df.columns):
    st.divider()
    st.subheader("Feature importance")
    top = importance_df.sort_values("importance_mean", ascending=False).head(15).sort_values("importance_mean")
    fig, ax = plt.subplots(figsize=(7, 5))
    ax.barh(top["feature"], top["importance_mean"], xerr=top["importance_std"] if "importance_std" in top else None)
    ax.set_xlabel("Mean drop in validation ROC-AUC when shuffled")
    fig.tight_layout()
    st.pyplot(fig)
    st.caption("Permutation importance reflects model reliance under the evaluation sample. It is not causal evidence; correlated inputs can distort rankings.")

st.divider()
st.subheader("Export a shareable experiment snapshot")
export_payload = {
    "project": "HiggsLens",
    "data_metadata": metadata,
    "selected_model": chosen_model,
    "target_signal_efficiency": target_eff,
    "threshold_selected_on_validation": threshold,
    "test_metrics_at_frozen_threshold": {
        "signal_efficiency": float(recall_score(yt, pred, zero_division=0)),
        "background_rejection": float(tn / max(tn + fp, 1)),
        "precision": float(precision_score(yt, pred, zero_division=0)),
        "f1": float(f1_score(yt, pred, zero_division=0)),
        "roc_auc": float(roc_auc_score(yt, pt)),
        "average_precision": float(average_precision_score(yt, pt)),
        "brier_score": float(brier_score_loss(yt, pt)),
    },
    "caveat": "Simulated benchmark data; exploratory tool, not a discovery claim or full physics analysis."
}
st.download_button("Download experiment snapshot (JSON)", json.dumps(export_payload, indent=2).encode("utf-8"), file_name="higgslens_snapshot.json", mime="application/json")
